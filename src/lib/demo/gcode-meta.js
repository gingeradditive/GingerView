/**
 * Metadati e miniature di un G-code di OrcaSlicer, nel formato di Moonraker.
 *
 * Lo usano sia lo script che prepara i file della demo
 * (`tools/import-gcode.mjs`, in Node) sia il simulatore quando un visitatore
 * carica un file dal telefono: per questo è JavaScript puro, senza dipendenze.
 *
 * Orca scrive i dati in due posti: un'intestazione corta in testa e il blocco
 * di configurazione in coda. Chi chiama passa il testo intero, o la testa e la
 * coda concatenate quando il file è grande.
 */

/**
 * `'14h 3m 20s'`, `'1d 2h 0m 0s'` → secondi.
 * @param {string} text
 * @returns {number | undefined}
 */
export function parseDuration(text) {
	const units = { d: 86400, h: 3600, m: 60, s: 1 };
	let total = 0;
	let found = false;
	for (const match of text.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)) {
		total += Number(match[1]) * units[/** @type {'d'|'h'|'m'|'s'} */ (match[2])];
		found = true;
	}
	return found ? Math.round(total) : undefined;
}

/**
 * Il valore della prima riga `; chiave = valore` (o `; chiave: valore`).
 * @param {string} text
 * @param {string} key
 * @returns {string | undefined}
 */
function readValue(text, key) {
	const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
	const match = text.match(new RegExp(`^;\\s*${escaped}\\s*[=:]\\s*(.*)$`, 'm'));
	if (!match) return undefined;
	return match[1].trim().replace(/^"(.*)"$/, '$1');
}

/**
 * @param {string} text
 * @param {string} key
 * @returns {number | undefined}
 */
function readNumber(text, key) {
	const value = readValue(text, key);
	if (value === undefined) return undefined;
	// Le liste multi-estrusore ("220,220") valgono per il primo.
	const number = Number.parseFloat(value.split(/[,;]/)[0]);
	return Number.isFinite(number) ? number : undefined;
}

/**
 * Le miniature incluse nel file, dalla più grande.
 * @param {string} text
 * @returns {{ width: number, height: number, base64: string }[]}
 */
export function extractThumbnails(text) {
	const thumbnails = [];
	const pattern =
		/; thumbnail(?:_PNG)? begin (\d+)x(\d+) \d+\r?\n([\s\S]*?)\r?\n; thumbnail(?:_PNG)? end/g;
	for (const match of text.matchAll(pattern)) {
		const base64 = match[3]
			.split('\n')
			.map((line) => line.replace(/^;\s?/, '').trim())
			.join('');
		if (base64) {
			thumbnails.push({ width: Number(match[1]), height: Number(match[2]), base64 });
		}
	}
	return thumbnails.sort((a, b) => b.width * b.height - a.width * a.height);
}

/**
 * I metadati che GingerView legge da `/server/files/metadata`.
 * @param {string} text
 * @returns {Record<string, string | number>}
 */
export function parseGcodeMetadata(text) {
	/** @type {Record<string, string | number | undefined>} */
	const metadata = {};

	const generated = text.match(/^; generated by (\S+) (\S+)/m);
	if (generated) {
		metadata.slicer = generated[1];
		metadata.slicer_version = generated[2];
	}

	const estimated = readValue(text, 'estimated printing time (normal mode)');
	metadata.estimated_time = estimated ? parseDuration(estimated) : undefined;

	metadata.layer_height = readNumber(text, 'layer_height');
	metadata.first_layer_height = readNumber(text, 'first_layer_height');
	metadata.object_height = readNumber(text, 'max_z_height');
	metadata.filament_total = readNumber(text, 'filament used [mm]');
	metadata.filament_weight_total =
		readNumber(text, 'total filament used [g]') ?? readNumber(text, 'filament used [g]');
	metadata.filament_type = readValue(text, 'filament_type');
	metadata.filament_name = readValue(text, 'filament_settings_id');
	metadata.nozzle_diameter = readNumber(text, 'nozzle_diameter');
	metadata.first_layer_extr_temp = readNumber(text, 'first_layer_temperature');
	metadata.first_layer_bed_temp =
		readNumber(text, 'first_layer_bed_temperature') ??
		readNumber(text, 'hot_plate_temp_initial_layer');
	metadata.extruder_temp =
		readNumber(text, 'nozzle_temperature') ?? readNumber(text, 'temperature');
	metadata.bed_temp = readNumber(text, 'hot_plate_temp') ?? readNumber(text, 'bed_temperature');

	/** @type {Record<string, string | number>} */
	const clean = {};
	for (const [key, value] of Object.entries(metadata)) {
		if (value !== undefined && value !== '') clean[key] = value;
	}
	return clean;
}
